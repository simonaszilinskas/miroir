"""Result files `eval/results/<round>/<step>-<option>.json` and the summary in docs/results.md.

One file per option run in a round. It holds one `SetScore` per (test set, half, gallery) the
option was scored on, each with its per-query ranks, so any two runs can be compared later with
a paired bootstrap. Files are validated on write and on read: a stored mean that does not match
its per-query values is refused.
"""

from __future__ import annotations

import logging
import re
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from pydantic import ConfigDict, TypeAdapter, ValidationError

from miroir.config import REPO_ROOT, SEED
from miroir.eval.notfound import MATCH_RATE, WRONG_TARGET, NotFoundScore
from miroir.eval.scoring import (
    HIT_KS,
    RESAMPLES,
    Interval,
    QueryScore,
    ScoreResult,
    bootstrap,
    per_query_values,
)
from miroir.eval.vectors import RunInfo

logger = logging.getLogger(__name__)

SCHEMA_VERSION = 1
SUMMARY_START = "<!-- summary:start (generated by `miroir eval summary`; do not edit) -->"
SUMMARY_END = "<!-- summary:end -->"

_EPS = 1e-9


def results_dir() -> Path:
    return REPO_ROOT / "eval" / "results"


def results_md() -> Path:
    return REPO_ROOT / "docs" / "results.md"


@dataclass(frozen=True, slots=True)
class SetScore:
    """Scores of one option on one test set half against one gallery."""

    __pydantic_config__ = ConfigDict(extra="forbid")

    test_set: str
    """"T1"..."T8", or a benchmark with its direction, e.g. "amstertime-old"."""
    half: str
    """"tune", "sealed", or "all" for benchmarks without halves."""
    gallery: str
    gallery_images: int
    gallery_entities: int
    queries: int
    skipped_no_answer: int
    ap_max_rank: int | None
    hit_at_1: Interval
    hit_at_5: Interval
    hit_at_10: Interval
    map: Interval
    per_query: tuple[QueryScore, ...]

    def __post_init__(self) -> None:
        if self.queries != len(self.per_query) or self.queries == 0:
            msg = f"{self.test_set}: {self.queries} queries but {len(self.per_query)} scores"
            raise ValueError(msg)
        for q in self.per_query:
            if q.rank < 1 or not 0 <= q.ap <= 1:
                msg = f"{self.test_set}: impossible score {q}"
                raise ValueError(msg)
        values = per_query_values(self.per_query)
        for name, interval in self.metrics().items():
            if abs(float(values[name].mean()) - interval.value) > _EPS:
                msg = f"{self.test_set} {name}: stored {interval.value} != per-query mean"
                raise ValueError(msg)
            if not 0 <= interval.low <= interval.high <= 1:
                msg = f"{self.test_set} {name}: interval {interval} is out of order"
                raise ValueError(msg)

    @property
    def key(self) -> tuple[str, str, str]:
        return (self.test_set, self.half, self.gallery)

    def metrics(self) -> dict[str, Interval]:
        return {
            "hit@1": self.hit_at_1,
            "hit@5": self.hit_at_5,
            "hit@10": self.hit_at_10,
            "map": self.map,
        }


@dataclass(frozen=True, slots=True)
class RunResult:
    """Everything one option scored in one round."""

    __pydantic_config__ = ConfigDict(extra="forbid")

    schema_version: int
    round: str
    step: str
    option: str
    """File-name label, e.g. "A1-dinov2-vitl14-224"."""
    updated: date
    vector_run: str
    """Run folder of the gallery vectors (technical spec §7.1)."""
    query_vector_run: str
    """Run folder of the query vectors; the same as `vector_run` when queries are POP images."""
    vectors: RunInfo
    bootstrap_resamples: int
    bootstrap_seed: int
    scores: tuple[SetScore, ...]
    not_found: tuple[NotFoundScore, ...] = ()
    """The "not found" measure (T8), when scored."""

    def __post_init__(self) -> None:
        if self.schema_version != SCHEMA_VERSION:
            msg = f"schema_version {self.schema_version}, expected {SCHEMA_VERSION}"
            raise ValueError(msg)
        keys = [s.key for s in self.scores]
        found_keys = [s.key for s in self.not_found]
        if len(set(keys)) != len(keys) or len(set(found_keys)) != len(found_keys):
            msg = f"{self.step}-{self.option}: the same set, half and gallery appear twice"
            raise ValueError(msg)


_RESULT = TypeAdapter(RunResult)


class ResultFormatError(ValueError):
    """A result file breaks the schema."""


def set_score(
    result: ScoreResult, *, test_set: str, half: str, gallery: str, seed: int = SEED
) -> SetScore:
    """Turn raw per-query scores into a `SetScore` with bootstrap intervals."""
    if HIT_KS != (1, 5, 10):
        msg = "SetScore stores hit@1, hit@5 and hit@10 only"
        raise AssertionError(msg)
    values = per_query_values(result.per_query)
    return SetScore(
        test_set=test_set,
        half=half,
        gallery=gallery,
        gallery_images=result.gallery_images,
        gallery_entities=result.gallery_entities,
        queries=len(result.per_query),
        skipped_no_answer=result.skipped_no_answer,
        ap_max_rank=result.ap_max_rank,
        hit_at_1=bootstrap(values["hit@1"], seed=seed),
        hit_at_5=bootstrap(values["hit@5"], seed=seed),
        hit_at_10=bootstrap(values["hit@10"], seed=seed),
        map=bootstrap(values["map"], seed=seed),
        per_query=result.per_query,
    )


def read_result(path: Path) -> RunResult:
    try:
        return _RESULT.validate_json(path.read_bytes())
    except ValidationError as err:
        msg = f"{path}: {err}"
        raise ResultFormatError(msg) from err


def write_result(
    path: Path,
    *,
    round_id: str,
    step: str,
    option: str,
    vector_run: str,
    query_vector_run: str,
    vectors: RunInfo,
    scores: Sequence[SetScore],
    today: date,
    not_found: Sequence[NotFoundScore] = (),
) -> RunResult:
    """Write scores into the option's file, replacing entries with the same set, half, gallery."""
    kept: tuple[SetScore, ...] = ()
    kept_found: tuple[NotFoundScore, ...] = ()
    if path.exists():
        old = read_result(path)
        if old.vector_run != vector_run or old.query_vector_run != query_vector_run:
            msg = (
                f"{path} holds scores of vector run {old.vector_run}; "
                f"use a new option label for {vector_run}"
            )
            raise ValueError(msg)
        new_keys = {s.key for s in scores}
        kept = tuple(s for s in old.scores if s.key not in new_keys)
        new_found = {s.key for s in not_found}
        kept_found = tuple(s for s in old.not_found if s.key not in new_found)
    result = RunResult(
        schema_version=SCHEMA_VERSION,
        round=round_id,
        step=step,
        option=option,
        updated=today,
        vector_run=vector_run,
        query_vector_run=query_vector_run,
        vectors=vectors,
        bootstrap_resamples=RESAMPLES,
        bootstrap_seed=SEED,
        scores=tuple(sorted((*kept, *scores), key=lambda s: s.key)),
        not_found=tuple(sorted((*kept_found, *not_found), key=lambda s: s.key)),
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(_RESULT.dump_json(result, indent=1) + b"\n")
    logger.info("wrote %s", path)
    return result


def find_set_score(result: RunResult, test_set: str, half: str, gallery: str) -> SetScore:
    for s in result.scores:
        if s.key == (test_set, half, gallery):
            return s
    msg = f"{result.step}-{result.option} has no score for {test_set}/{half}/{gallery}"
    raise KeyError(msg)


def summary_table(results: Sequence[RunResult]) -> str:
    """Markdown table: one row per scored set, sorted by round, set, half, gallery, then mAP."""
    rows: list[tuple[tuple[str, str, str, str, float], str]] = []
    for result in results:
        for s in result.scores:
            cells = [
                result.round,
                s.test_set,
                s.half,
                s.gallery,
                f"{result.step}-{result.option}",
                result.vectors.model,
                str(result.vectors.resolution),
                result.vectors.pooling,
                f"{s.queries:,}",
                *(_pct(i) for i in (s.hit_at_1, s.hit_at_5, s.hit_at_10, s.map)),
            ]
            sort_key = (result.round, s.test_set, s.half, s.gallery, -s.map.value)
            rows.append((sort_key, "| " + " | ".join(cells) + " |"))
    header = (
        "| Round | Set | Half | Gallery | Run | Model | Px | Pooling | Queries "
        "| Hit@1 | Hit@5 | Hit@10 | mAP |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|"
    )
    body = "\n".join(line for _, line in sorted(rows))
    note = (
        "Each cell: value in %, then the 95% bootstrap interval "
        f"({RESAMPLES:,} resamples over queries)."
    )
    table = f"{note}\n\n{header}\n{body}" if body else f"{note}\n\n{header}"
    found = not_found_table(results)
    return f"{table}\n\n{found}" if found else table


def not_found_table(results: Sequence[RunResult]) -> str:
    """Markdown table of the "not found" measure, one row per scored T8 half. Empty if none."""
    rows: list[tuple[tuple[str, str, str, str, float], str]] = []
    for result in results:
        for s in result.not_found:
            cells = [
                result.round,
                s.test_set,
                s.half,
                s.gallery,
                f"{result.step}-{result.option}",
                " + ".join(s.in_index_sets),
                f"{len(s.in_index):,}",
                f"{len(s.not_found):,}",
                _pct(s.wrong_confident),
                _pct(s.match_rate_at_target),
            ]
            sort_key = (result.round, s.test_set, s.half, s.gallery, s.wrong_confident.value)
            rows.append((sort_key, "| " + " | ".join(cells) + " |"))
    if not rows:
        return ""
    header = (
        "| Round | Set | Half | Gallery | Run | In-index sets | In-index | Not found "
        f"| Wrong but confident, {100 * MATCH_RATE:.0f}% matched "
        f"| Matched, {100 * WRONG_TARGET:.0f}% wrong |\n"
        "|---|---|---|---|---|---|---|---|---|---|"
    )
    note = (
        "Not found (T8): confidence is the top entity's score. Lower is better for "
        '"wrong but confident", higher for "matched".'
    )
    body = "\n".join(line for _, line in sorted(rows))
    return f"{note}\n\n{header}\n{body}"


def rebuild_summary(directory: Path, markdown: Path) -> int:
    """Rewrite the generated block in results.md from every result file. Returns the file count."""
    files = sorted(directory.glob("R*/*.json"))
    results = [read_result(f) for f in files]
    text = markdown.read_text(encoding="utf-8")
    block = f"{SUMMARY_START}\n{summary_table(results)}\n{SUMMARY_END}"
    pattern = re.compile(re.escape(SUMMARY_START) + r".*?" + re.escape(SUMMARY_END), re.DOTALL)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.rstrip("\n") + f"\n\n## Summary of all runs\n\n{block}\n"
    markdown.write_text(text, encoding="utf-8")
    return len(files)


def _pct(interval: Interval) -> str:
    return f"{100 * interval.value:.1f} [{100 * interval.low:.1f}, {100 * interval.high:.1f}]"
